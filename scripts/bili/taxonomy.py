PLAT_ORDER = ["steam", "pc", "switch", "mobile", "web", "console", "itch", "booth", "dlsite", "freem"]

PLAT_NAMES = {k: n for k, n, _ in PLAT_RULES}


def strip_quotes(s: str) -> str:
    """去掉书名号、引号、空格，用于名称归一化。"""
    if not s:
        return ""
    s = unicodedata.normalize("NFKC", s)
    s = re.sub(r"[《》「」『』“”\"'’‘\[\]【】]", "", s)
    s = re.sub(r"\s+", "", s)
    return s.strip(" ：:·-—_/／、,，.。")


def norm_key(s: str) -> str:
    """归一化 key：小写 + 去标点空白，用于去重与匹配。"""
    s = strip_quotes(s or "")
    s = re.sub(r"[·・:：,，。\.\-—_（）()／/、!！?？&＆]", "", s)
    return s.lower()


def split_names(raw: str):
    """把「甲（乙）」「A/B」拆成 [主名, 副名...]"""
    raw = unicodedata.normalize("NFKC", raw or "")
    raw = re.sub(r"[《》「」『』]", "", raw).strip()
    if not raw:
        return []
    out = []
    # 括号里的原名
    m = re.match(r"^(.*?)[（(]([^）)]+)[）)]\s*$", raw)
    if m:
        out.extend([m.group(1).strip(), m.group(2).strip()])
    for piece in re.split(r"[/／、]", raw):
        piece = piece.strip()
        if piece:
            out.append(piece)
    seen, res = set(), []
    for x in out:
        k = norm_key(x)
        if k and k not in seen and len(k) >= 1:
            seen.add(k)
            res.append(x)
    return res


def match_platforms(text: str):
    """从平台字段/正文里抽平台集合。"""
    if not text:
        return []
    got = []
    for key, _, pat in PLAT_RULES:
        if re.search(pat, text, re.I):
            got.append(key)
    # 「各个平台都有」「多平台」这类模糊描述
    if re.search(r"各个平台|多平台|全平台|很多", text) and not got:
        got = ["pc", "mobile"]
    if "pc" in got and "steam" in got:
        pass
    # 去重并排序
    return [k for k in PLAT_ORDER if k in set(got)]


