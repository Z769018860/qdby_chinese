def parse_price(raw: str):
    """价格原文 → (元数值|None, 币种, 是否免费, 备注)
    支持「33」「免费」「1100日元」「$4.99」「目前只有demo」等写法。"""
    t = (raw or "").strip()
    if not t:
        return None, "", False, ""
    if re.search(r"免费|白嫖|不要钱|免费可通|免费下载", t) and not re.search(r"\d", t):
        return 0.0, "CNY", True, ""
    m = re.search(r"(\d+(?:\.\d+)?)", t)
    if not m:
        return None, "", False, t[:24]
    val = float(m.group(1))
    cur = "CNY"
    if re.search(r"日元|円|JPY", t):
        cur = "JPY"
        val = val * 0.048
    elif re.search(r"\$|美元|USD", t):
        cur = "USD"
        val = val * 7.2
    elif re.search(r"€|欧元|EUR", t):
        cur = "EUR"
        val = val * 7.8
    if re.search(r"免费", t) and val == 0:
        return 0.0, cur, True, ""
    # 「目前只有demo」「（得去日亚上和咸鱼找碟了）」这类带说明的
    note = "" if re.match(r"^[¥$€]?\s*\d+(?:\.\d+)?\s*(?:元|块|日元|円)?$", t) else t[:24]
    return val, cur, False, note


def price_bucket(val, is_free):
    if is_free or (val is not None and val == 0):
        return "free"
    if val is None:
        return "unknown"
    if val <= 30:
        return "low"
    if val <= 70:
        return "mid"
    return "high"


def scan(text: str, table):
    """返回命中该项的集合（保持表内顺序）。"""
    if not text:
        return []
    return [key for key, _, pat in table if re.search(pat, text)]


def primary_genre(text: str):
    for key, _, pat in GENRES:
        if re.search(pat, text or ""):
            return key
    return ""


def vid_dur_bucket(sec: int) -> str:
    """视频时长档（分钟）"""
    m = (sec or 0) / 60
    if m <= 5:
        return "v_xs"
    if m <= 20:
        return "v_s"
    if m <= 60:
        return "v_m"
    return "v_l"


def game_len_bucket(hours: float) -> str:
    """游戏体量档：由该游戏全部相关视频的累计时长推断"""
    if hours < 2:
        return "g_xs"
    if hours < 8:
        return "g_s"
    if hours < 20:
        return "g_m"
    return "g_l"


