def parse_price(raw: str):
    """价格原文 → (元数值|None, 币种, 是否免费, 备注)
    支持「33」「免费」「1100日元」「$4.99」「目前只有demo」等写法。"""
    t = (raw or "").strip()
    if not t:
        return None, "", False, ""
    if re.search(r"免费|白嫖|不要钱|免费可通|免费下载", t) and not re.search(r"\d", t):
        return 0.0, "CNY", True, ""
    m = re.search(r"(\d+(?:\.\d+)?)", t)
    if not m:
        return None, "", False, t[:24]
    val = float(m.group(1))
    cur = "CNY"
    if re.search(r"日元|円|JPY", t):
        cur = "JPY"
        val = val * 0.048
    elif re.search(r"\$|美元|USD", t):
        cur = "USD"
        val = val * 7.2
    elif re.search(r"€|欧元|EUR", t):
        cur = "EUR"
        val = val * 7.8
    if re.search(r"免费", t) and val == 0:
        return 0.0, cur, True, ""
    # 「目前只有demo」「（得去日亚上和咸鱼找碟了）」这类带说明的
    note = "" if re.match(r"^[¥$€]?\s*\d+(?:\.\d+)?\s*(?:元|块|日元|円)?$", t) else t[:24]
    return val, cur, False, note


def price_bucket(val, is_free):
    if is_free or (val is not None and val == 0):
        return "free"
    if val is None:
        return "unknown"
    if val <= 30:
        return "low"
    if val <= 70:
        return "mid"
    return "high"


# 手游 / 抽卡 / 网游类内容：这些不是单机实况，体量与时长统计都排除
MOBILE_PAT = re.compile(
    r"忘却前夜|明日方舟|终末地|剑网\s*3|剑网三|剑三|\bjjc\b|妖恋奇谭|食物语|梦间集|"
    r"融灾|抽卡实况|卡池|抽卡记录|公主连结|公主链接|\bPCR\b", re.I)


def is_mobile_title(title: str) -> bool:
    return bool(MOBILE_PAT.search(title or ""))


def scan(text: str, table):
    """返回命中该项的集合（保持表内顺序）。"""
    if not text:
        return []
    return [key for key, _, pat in table if re.search(pat, text)]


def primary_genre(text: str):
    for key, _, pat in GENRES:
        if re.search(pat, text or ""):
            return key
    return ""


def vid_dur_bucket(sec: int) -> str:
    """视频时长档（分钟）"""
    m = (sec or 0) / 60
    if m <= 5:
        return "v_xs"
    if m <= 20:
        return "v_s"
    if m <= 60:
        return "v_m"
    return "v_l"


def game_len_bucket(hours: float) -> str:
    """游戏体量档：取该游戏「最长的一条单机实况投稿（含全部分 P）」的时长

    早先是「该游戏所有投稿时长之和」，结果系列节目把这个数字撑爆了：
    忘却前夜每两周一条融灾记录、明日方舟一堆抽卡实况，加起来几百小时，
    全被判成长篇 20h+，体量这一栏就失去意义了。
    现在只看单条投稿：一条投稿的全部分 P 加起来，才是「打完一遍」的量级。"""
    if hours < 2:
        return "g_xs"
    if hours < 8:
        return "g_s"
    if hours < 20:
        return "g_m"
    return "g_l"


